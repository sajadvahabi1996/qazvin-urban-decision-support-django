import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(projectRoot, "webgis", "static", "webgis", "js", "src");
const outputFile = path.join(projectRoot, "webgis", "static", "webgis", "js", "app.bundle.js");
const modules = [
  "config.js",
  "utils.js",
  "map-layers.js",
  "dashboard.js",
  "neighborhood-search.js",
];

const sources = modules.map((moduleName) => {
  const modulePath = path.join(sourceDir, moduleName);
  const source = fs.readFileSync(modulePath, "utf8");
  new vm.Script(source, { filename: moduleName });
  return source.trimEnd();
});

const bundle =
  `/* Generated by scripts/build_frontend.mjs. Edit js/src modules instead. */\n` +
  sources.join("\n\n/* module boundary */\n\n") +
  "\n";

// Validate the combined file before replacing the last known-good bundle.
new vm.Script(bundle, { filename: "app.bundle.js" });
fs.writeFileSync(outputFile, bundle, "utf8");

console.log(
  `Built ${path.relative(projectRoot, outputFile)} from ${modules.length} source modules.`,
);
